#!/usr/bin/env python3
"""Write runtime config.env from the saved Orca environment endpoint.

Reads only the websocket URL. Never copies deviceToken, publicKey, or authToken.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from urllib.parse import urlparse


def endpoint_from_environments(path: Path) -> tuple[str, int]:
    data = json.loads(path.read_text())
    environments = data.get("environments") if isinstance(data, dict) else None
    if not isinstance(environments, list):
        raise SystemExit(f"no environments in {path}")
    for env in environments:
        if not isinstance(env, dict):
            continue
        for ep in env.get("endpoints") or []:
            if not isinstance(ep, dict):
                continue
            raw = ep.get("endpoint")
            if not isinstance(raw, str) or not raw.startswith("ws"):
                continue
            parsed = urlparse(raw)
            if not parsed.hostname or parsed.hostname == "127.0.0.1":
                continue
            port = parsed.port or 6768
            return parsed.hostname, port
    raise SystemExit(f"no remote websocket endpoint in {path}")


def main() -> None:
    home = Path.home()
    runtime = Path(os.environ.get("ORCA_NETD_HOME") or home / ".local/share/orca-netd")
    target = runtime / "config.env"
    refresh = "--refresh" in sys.argv
    if target.exists() and not refresh:
        print(f"keep {target}")
        return
    host = os.environ.get("ORCA_NETD_DEST_HOST")
    port = os.environ.get("ORCA_NETD_DEST_PORT")
    if not host:
        source = Path(
            os.environ.get("ORCA_ENVIRONMENTS")
            or home / "Library/Application Support/orca/orca-environments.json"
        )
        host, parsed_port = endpoint_from_environments(source)
        port = port or str(parsed_port)
    port = port or "6768"
    runtime.mkdir(parents=True, exist_ok=True)
    body = "\n".join(
        [
            "# Generated by projects/orca-netd/install.sh. Not a credential file.",
            f"ORCA_NETD_DEST_HOST={host}",
            f"ORCA_NETD_DEST_PORT={port}",
            "ORCA_NETD_SOCKS_HOST=127.0.0.1",
            "ORCA_NETD_SOCKS_PORT=1055",
            "ORCA_NETD_FORWARD_PORT=16768",
            "",
        ]
    )
    target.write_text(body)
    os.chmod(target, 0o600)
    print(f"wrote {target} dest_port={port}")


if __name__ == "__main__":
    main()
